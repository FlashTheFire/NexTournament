def t(key: str, lang: str = "en", **kwargs: Any) -> str:
    """
    Translates a key into the target language with variable formatting.
    Falls back to English if the translation key is missing.
    """
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    text_template = lang_dict.get(key, TRANSLATIONS["en"].get(key, f"[{key}]"))
    try:
        return text_template.format(**kwargs)
    except Exception:
        return text_template


